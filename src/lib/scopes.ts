export const SCOPE_DESCRIPTIONS: Record<string, string> = Object.fromEntries(
  [...SYNTAX_SCOPES, ...UI_SCOPES].map((s) => [s.scope, s.description]),
);

export type ScopeGroup = 'syntax' | 'markup' | 'diff' | 'ui' | 'diagnostics';

export function scopeGroup(scope: string): ScopeGroup {
  if (/^ui(\.|$)/.test(scope)) return 'ui';
  if (/^(diagnostic|warning|error|info|hint)(\.|$)/.test(scope)) return 'diagnostics';
  if (/^markup(\.|$)/.test(scope)) return 'markup';
  if (/^diff(\.|$)/.test(scope)) return 'diff';
  return 'syntax';
}

